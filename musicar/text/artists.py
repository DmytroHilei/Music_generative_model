ALIAS, ARIA_ALIAS = {}, {}
for _id, _a in ARTISTS.items():
    for _k in map(key, _a['en'] + _a['aka']):
        assert ALIAS.setdefault(_k, _id) == _id, f'{_k!r}: {ALIAS[_k]} and {_id}'
    for _k in map(key, _a['aria']):
        assert ARIA_ALIAS.setdefault(_k, _id) == _id, f'{_k!r}: {ARIA_ALIAS[_k]} and {_id}'


def resolve(raw, source='gigamidi'):
    """Artist id of a raw name ('Chopin, Frédéric', Aria 'chopin'), or None for names not in ARTISTS. source 'aria'
    also accepts the Aria-only surnames ('williams' -> John Williams)."""
    if not raw:
        return None
    k = key(raw)
    if source == 'aria' and k in ARIA_ALIAS:
        return ARIA_ALIAS[k]
    return ALIAS.get(k)


def named_in_uk(artist_id):
    """Whether Ukrainian captions can name the artist (Ukrainian forms, or a band's Latin name)."""
    a = ARTISTS[artist_id]
    return bool(a['uk']) or a['band']
