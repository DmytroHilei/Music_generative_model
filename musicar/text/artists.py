"""
Composer / artist names for captions (musicar/text/captions.py), hand-written 2026-10-20 from the names with the most
files: the GigaMIDI v2 'artist' field (label rows 'gigamidi') and the Aria 'composer' metadata (label rows 'aria',
lower-case surnames).

ARTISTS: id -> dict(
  en:    English names, the usual one first ('Chopin', 'Frédéric Chopin'); bands with 'the' as in mid-sentence
  uk:    Ukrainian (nominative, genitive) pairs ('Шопен', 'Шопена'); artists without them and without band=True are
         named in English captions only
  band:  a group: Ukrainian captions keep the Latin name ('пісня гурту Queen'), as Ukrainian texts do
  aka:   more spellings as lookup keys (key()), e.g. GigaMIDI's transliterations from Russian
  aria:  Aria composer keys that are ambiguous elsewhere: 'williams' is John Williams only in Aria)
resolve(raw, source) -> id or None.
"""

import re
import unicodedata


def key(raw):
    """Lookup key of a raw name: whitespace runs collapsed, '(1872-1915)' / '(The)' dropped, 'Last, First' ->
    'First Last', accents stripped, lower case, a leading 'the' dropped, punctuation -> spaces:
    'Bach, Johann Sebastian' -> 'johann sebastian bach', 'Beatles (The)' -> 'beatles'."""
    s = ' '.join(str(raw).split())
    s = re.sub(r'\s*\((?:[^)]*\d{3,4}[^)]*|the)\)', '', s, flags=re.I).strip()
    if s.count(',') == 1:
        last, first = (x.strip() for x in s.split(','))
        if first and len(first.split()) <= 4:
            s = f'{first} {last}'
    s = ''.join(c for c in unicodedata.normalize('NFKD', s) if not unicodedata.combining(c)).lower()
    s = re.sub(r'^the\s+', '', s)
    return re.sub(r'[\W_]+', ' ', s).strip()


def _e(en, uk=(), band=False, aka=(), aria=()):
    return dict(en=list(en), uk=list(uk), band=band, aka=list(aka), aria=list(aria))


